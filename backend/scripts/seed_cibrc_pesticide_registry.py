def seed_cibrc_registry():
    use_pg = is_postgres_active()
    placeholder = "%s" if use_pg else "?"
    print(f"[*] Initializing CIBRC Pesticide Registry Table in {'PostgreSQL' if use_pg else 'SQLite'}...")

    # Create table if not present
    if use_pg:
        create_sql = """
        CREATE TABLE IF NOT EXISTS cibrc_pesticide_registry (
            id BIGSERIAL PRIMARY KEY,
            category VARCHAR(50) NOT NULL,
            pesticide_name VARCHAR(200) NOT NULL,
            active_ingredient VARCHAR(150) NOT NULL,
            formulation VARCHAR(80),
            crop VARCHAR(100) NOT NULL,
            crop_key VARCHAR(50) NOT NULL,
            target_pest_or_disease TEXT NOT NULL,
            ai_dose VARCHAR(100),
            formulation_dose VARCHAR(120),
            dilution_water_liters VARCHAR(100),
            waiting_period_days VARCHAR(60),
            pump_dose_15l VARCHAR(100),
            application_method VARCHAR(150) DEFAULT 'Foliar Spray',
            toxicity_band VARCHAR(30) DEFAULT 'green',
            toxicity_label TEXT,
            safety_warnings TEXT,
            is_approved BOOLEAN DEFAULT TRUE,
            payload JSONB DEFAULT '{}'::jsonb,
            created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
            updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
        );
        CREATE INDEX IF NOT EXISTS idx_cibrc_crop_key ON cibrc_pesticide_registry (crop_key);
        CREATE INDEX IF NOT EXISTS idx_cibrc_active_ing ON cibrc_pesticide_registry (active_ingredient);
        CREATE INDEX IF NOT EXISTS idx_cibrc_category ON cibrc_pesticide_registry (category);
        """
    else:
        create_sql = """
        CREATE TABLE IF NOT EXISTS cibrc_pesticide_registry (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            category TEXT NOT NULL,
            pesticide_name TEXT NOT NULL,
            active_ingredient TEXT NOT NULL,
            formulation TEXT,
            crop TEXT NOT NULL,
            crop_key TEXT NOT NULL,
            target_pest_or_disease TEXT NOT NULL,
            ai_dose TEXT,
            formulation_dose TEXT,
            dilution_water_liters TEXT,
            waiting_period_days TEXT,
            pump_dose_15l TEXT,
            application_method TEXT DEFAULT 'Foliar Spray',
            toxicity_band TEXT DEFAULT 'green',
            toxicity_label TEXT,
            safety_warnings TEXT,
            is_approved INTEGER DEFAULT 1,
            payload TEXT DEFAULT '{}',
            created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
            updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
        );
        """

    with get_db_cursor() as cursor:
        cursor.execute(create_sql)

    print("[*] Inserting CIBRC statutory approved pesticide entries...")

    insert_sql = f"""
    INSERT INTO cibrc_pesticide_registry (
        category, pesticide_name, active_ingredient, formulation,
        crop, crop_key, target_pest_or_disease, ai_dose,
        formulation_dose, dilution_water_liters, waiting_period_days,
        pump_dose_15l, application_method, toxicity_band, toxicity_label,
        safety_warnings, is_approved, payload
    ) VALUES (
        {placeholder}, {placeholder}, {placeholder}, {placeholder},
        {placeholder}, {placeholder}, {placeholder}, {placeholder},
        {placeholder}, {placeholder}, {placeholder},
        {placeholder}, {placeholder}, {placeholder}, {placeholder},
        {placeholder}, {placeholder}, {placeholder}
    )
    """

    count = 0
    with get_db_cursor() as cursor:
        # Clear existing records to ensure fresh idempotent seed
        cursor.execute("DELETE FROM cibrc_pesticide_registry;")

        for item in CIBRC_REGISTRY_DATA:
            payload_data = {
                "common_brands": item.get("common_brands", []),
                "pesticide_name": item["pesticide_name"],
                "active_ingredient": item["active_ingredient"],
                "formulation": item["formulation"],
                "crop": item["crop"],
                "target_pest_or_disease": item["target_pest_or_disease"],
                "waiting_period_days": item["waiting_period_days"],
                "pump_dose_15l": item["pump_dose_15l"]
            }
            payload_str = json.dumps(payload_data)

            params = (
                item["category"],
                item["pesticide_name"],
                item["active_ingredient"],
                item["formulation"],
                item["crop"],
                item["crop_key"],
                item["target_pest_or_disease"],
                item["ai_dose"],
                item["formulation_dose"],
                item["dilution_water_liters"],
                item["waiting_period_days"],
                item["pump_dose_15l"],
                item["application_method"],
                item["toxicity_band"],
                item["toxicity_label"],
                item["safety_warnings"],
                True if use_pg else 1,
                payload_str
            )
            cursor.execute(insert_sql, params)
            count += 1

    print(f"[+] Successfully seeded {count} official CIBRC pesticide records into PostgreSQL!")


